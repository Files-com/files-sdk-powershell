        internal static Task<Models.Site> GetAsync(FilesConnection connection, Dictionary<string, object> parameters, FilesCallOptions options, CancellationToken cancellationToken)
        {
            return EngineCall.RunAsync(connection, options, cancellationToken, (client, requestOptions, token) => client.Sites.GetAsync(parameters, requestOptions, token), source => SiteBridge.Project(source, connection, options));
        }

        internal static Task<Models.UsageSnapshot> GetUsageAsync(FilesConnection connection, Dictionary<string, object> parameters, FilesCallOptions options, CancellationToken cancellationToken)
        {
            return EngineCall.RunAsync(connection, options, cancellationToken, (client, requestOptions, token) => client.Sites.GetUsageAsync(parameters, requestOptions, token), source => UsageSnapshotBridge.Project(source, connection, options));
        }

        internal static Task ExtendAutomationMigrationWindowAsync(FilesConnection connection, Dictionary<string, object> parameters, FilesCallOptions options, CancellationToken cancellationToken)
        {
            return EngineCall.RunAsync(connection, options, cancellationToken, (client, requestOptions, token) => client.Sites.ExtendAutomationMigrationWindowAsync(parameters, requestOptions, token));
        }

        internal static Task<Models.Site> UpdateAsync(FilesConnection connection, Dictionary<string, object> parameters, FilesCallOptions options, CancellationToken cancellationToken)
        {
            return EngineCall.RunAsync(connection, options, cancellationToken, (client, requestOptions, token) => client.Sites.UpdateAsync(Attachments.ForEngine(parameters), requestOptions, token), source => SiteBridge.Project(source, connection, options));
        }
